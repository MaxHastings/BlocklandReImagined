//! The v0.3.0 sized-join gate: a player joins a host whose Add-Ons total
//! at least 150 MB, over a throttled connection, with an empty download
//! cache. It measures the join and checks the loading screen's progress
//! moves all through the download, as a friend would see it.
//!
//! The Add-Ons are made at test time: client packs of incompressible bytes
//! (nothing compresses them on the way), with the room the other gates use.
//!
//! - `BRI_SIZED_JOIN_MB`: how much the packs hold in all (default 150).
//! - `BRI_SIZED_JOIN_MBIT`: the link's bandwidth each way in Mbit/s
//!   (default 100), with `BRI_SIZED_JOIN_LATENCY_MS` one-way delay
//!   (default 20) and a 100 ms router buffer.
//!
//! Numbers go to stderr as `[sized-join]` lines.
mod gate;

use anyhow::{Context, Result, ensure};
use bri_net::{
    impair::{ImpairedLink, Impairment},
    packages::PackageShelf,
    server::{self, ServerOptions},
};
use bri_package::{packages::Side, sync::Cache};
use bri_progress::{Progress, Stage, Unit};
use gate::*;
use std::{
    path::Path,
    sync::{
        Arc,
        atomic::{AtomicBool, Ordering},
    },
    time::{Duration, Instant},
};

/// Bytes per generated file: a pack is several files, as real ones are.
const FILE_BYTES: u64 = 8 * 1024 * 1024;
/// Packs the bytes are spread over.
const PACKS: u64 = 4;
/// The longest the download's progress may stand still.
const MAX_STILL: Duration = Duration::from_secs(2);

/// A client pack `id` in `dir` holding `bytes` of noise in `assets/`.
fn bulk_pack(dir: &Path, id: &str, bytes: u64, seed: u64) -> Result<()> {
    std::fs::create_dir_all(dir.join("assets"))?;
    std::fs::write(
        dir.join("package.json"),
        serde_json::to_vec_pretty(&serde_json::json!({
            "schema_version": 1,
            "id": id,
            "version": "1.0.0",
            "api": 1,
            "name": format!("Bulk {id}"),
            "description": "Generated by the sized-join gate: textures' worth of bytes.",
            "authors": ["Blockland ReImagined"],
            "license": "CC0-1.0",
            "provenance": { "source": "original" },
            "provides": []
        }))?,
    )?;
    let mut state = seed | 1;
    let mut left = bytes;
    let mut index = 0;
    while left > 0 {
        let n = left.min(FILE_BYTES);
        let mut data = Vec::with_capacity(n as usize);
        while (data.len() as u64) < n {
            // xorshift64*: incompressible and quick.
            state ^= state >> 12;
            state ^= state << 25;
            state ^= state >> 27;
            data.extend_from_slice(&state.wrapping_mul(0x2545_F491_4F6C_DD1D).to_le_bytes());
        }
        data.truncate(n as usize);
        std::fs::write(dir.join(format!("assets/bulk-{index:02}.bin")), data)?;
        left -= n;
        index += 1;
    }
    Ok(())
}

#[test]
fn stress_sized_join_over_a_throttled_link() -> Result<()> {
    let megabytes = env("BRI_SIZED_JOIN_MB", 150);
    let mbit = env("BRI_SIZED_JOIN_MBIT", 100).max(1);
    let latency = Duration::from_millis(env("BRI_SIZED_JOIN_LATENCY_MS", 20));
    let rate = mbit * 1_000_000 / 8;
    let total = megabytes * 1024 * 1024;

    // The packs, made in a scratch folder and staged into the host's root.
    let made = bri_content::testing::ScratchDir::new("sized-join-packs")?;
    let mut add_ons = Vec::new();
    for pack in 0..PACKS {
        let id = format!("bulk-pack-{pack}");
        let dir = made.path().join(&id);
        bulk_pack(
            &dir,
            &id,
            total.div_ceil(PACKS),
            (pack + 1).wrapping_mul(0x9E37_79B9_7F4A_7C15),
        )?;
        add_ons.push(AddOn::new(&id, dir, Side::Client));
    }
    let root = Root::new("sized-join", &add_ons)?;
    drop(made);
    let host = root.host(world("Sized join"))?;
    let base = root.base_packages(&host);
    let shelf = PackageShelf::new(root.path(), &root.set, &host.environment)?;

    let rt = tokio::runtime::Builder::new_multi_thread()
        .worker_threads(4)
        .enable_all()
        .build()?;
    let server = {
        let _in = rt.enter();
        server::start(
            host.session,
            ServerOptions {
                bind: "127.0.0.1:0".parse()?,
                environment: host.environment.clone(),
                spawn_points: host.spawn_points.clone(),
                certificate: None,
                map_loader: Some(host.setup.clone()),
                packages: Some(Arc::new(shelf)),
            },
        )?
    };
    let impairment = Impairment {
        latency,
        ..Impairment::NONE
    }
    .throttled(rate, Duration::from_millis(100));
    let link = rt.block_on(ImpairedLink::start(server.address, impairment, 0x51ed))?;

    // What the loading screen polls, sampled as often as it draws.
    let progress = Progress::default();
    let done = Arc::new(AtomicBool::new(false));
    let sampler = {
        let (progress, done) = (progress.clone(), done.clone());
        std::thread::spawn(move || {
            let start = Instant::now();
            let mut samples = Vec::new();
            while !done.load(Ordering::Relaxed) {
                samples.push((start.elapsed(), progress.snapshot()));
                std::thread::sleep(Duration::from_millis(20));
            }
            samples
        })
    };
    let identity_dir = tempfile::tempdir()?;
    let identity =
        bri_identity::ClientIdentity::load_or_create(identity_dir.path().join("friend.identity"))?;
    let cache_dir = tempfile::tempdir()?;
    let cache = Cache::open(cache_dir.path())?;
    let start = Instant::now();
    let (mut client, fetched) = rt.block_on(fetching_join(
        link.address,
        &server.certificate,
        "Friend",
        base,
        None,
        &identity,
        &cache,
        progress.clone(),
    ))?;
    let joined = start.elapsed();
    // In the world: the first update after the checkpoint.
    rt.block_on(async {
        tokio::time::timeout(Duration::from_secs(60), async {
            while client.replica.tick == 0 || !client.replica.poses.contains_key(&client.owner) {
                client.receive().await?;
            }
            Result::<()>::Ok(())
        })
        .await
        .context("no world after the join")?
    })?;
    let in_world = start.elapsed();
    done.store(true, Ordering::Relaxed);
    let samples = sampler.join().expect("the sampler ran");

    // Every pack, downloaded in full.
    let ids: Vec<&str> = fetched.iter().map(|(id, _)| id.as_str()).collect();
    let wanted: Vec<String> = (0..PACKS).map(|p| format!("bulk-pack-{p}")).collect();
    ensure!(ids == wanted, "downloaded {ids:?}, wanted {wanted:?}");
    let downloaded: u64 = fetched.iter().map(|(_, bytes)| bytes).sum();
    ensure!(
        downloaded >= total,
        "downloaded {downloaded} bytes, wanted at least {total}"
    );

    // Progress all through the download: bytes counting up to the total,
    // never standing still for long.
    let downloading: Vec<_> = samples
        .iter()
        .filter(|(_, s)| s.stage == Stage::DownloadingPackages)
        .collect();
    ensure!(
        !downloading.is_empty(),
        "the loading screen never showed the download"
    );
    let (first, last) = (downloading[0], downloading[downloading.len() - 1]);
    ensure!(
        last.1.unit == Unit::Bytes && last.1.total.is_some_and(|t| t >= total),
        "the download's progress has no byte total: {:?}",
        last.1
    );
    let mut still = Duration::ZERO;
    let mut since = first.0;
    let mut previous = first.1;
    for (at, snapshot) in &downloading {
        ensure!(
            snapshot.done >= previous.done,
            "progress went back from {} to {}",
            previous.done,
            snapshot.done
        );
        if snapshot.done != previous.done {
            since = *at;
        }
        still = still.max(*at - since);
        previous = *snapshot;
    }
    ensure!(
        still <= MAX_STILL,
        "the download's progress stood still for {still:?}"
    );
    let finished = progress
        .trail()
        .into_iter()
        .find(|s| s.stage == Stage::DownloadingPackages)
        .context("the download never finished as a stage")?;
    ensure!(
        finished.total.is_some_and(|t| finished.done == t),
        "the download stage ended at {} of {:?}",
        finished.done,
        finished.total
    );
    let download = last.0.saturating_sub(first.0);
    let throughput = downloaded as f64 / download.as_secs_f64().max(0.001);
    ensure!(
        throughput <= rate as f64 * 1.1,
        "{throughput:.0} B/s through a {rate} B/s link: the throttle did not hold"
    );
    ensure!(
        throughput >= rate as f64 * 0.3,
        "{throughput:.0} B/s through a {rate} B/s link: the download used under 30% of it"
    );
    eprintln!(
        "[sized-join] {} MB in {PACKS} packs over {mbit} Mbit/s, {} ms one way",
        downloaded / (1024 * 1024),
        latency.as_millis()
    );
    eprintln!(
        "[sized-join] joined in {:.1} s (download {:.1} s at {:.1} MB/s, {:.0}% of the link); \
         in the world at {:.1} s",
        joined.as_secs_f64(),
        download.as_secs_f64(),
        throughput / (1024.0 * 1024.0),
        100.0 * throughput / rate as f64,
        in_world.as_secs_f64()
    );
    eprintln!(
        "[sized-join] progress: {} readings while downloading, longest still {:?}; stages {:?}",
        downloading.len(),
        still,
        progress
            .trail()
            .iter()
            .map(|s| format!("{:?}", s.stage))
            .collect::<Vec<_>>()
    );
    eprintln!(
        "[sized-join] link: {} datagrams forwarded, {} dropped at the buffer",
        link.stats.forwarded.load(Ordering::Relaxed),
        link.stats.dropped.load(Ordering::Relaxed)
    );
    drop(client);
    rt.block_on(server.stop())?;
    drop(link);
    Ok(())
}
